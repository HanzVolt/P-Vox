"""Polivoks load screen assets.

  tools/gen_poli_boot.py           write firmware/src/poli_boot_logo.h and firmware/src/poli_boot_voice.h
  tools/gen_poli_boot.py --check   regenerate in memory and compare with the checked-in headers (exit 1 if not equal)
  tools/gen_poli_boot.py --wav OUT write the clip as the firmware decodes it (16 kHz, IMA-ADPCM decoded) to OUT

Logo: assets/logo/hv_splash_b.png, byte for byte the FORM / HanzVolt HV boot splash (B) of FORM 1.3
(wt-formfm-1.3 tools/logo/hv_splash_b.png, sha256 fbb73add...). Encoded exactly as FORM's tools/gen_logo.py does
(16-colour palette as RGB565, RLE bytes (run - 1) << 4 | index, runs of 1..16).
(C) Hans Volt (HanzVolt), all rights reserved. NOT GPL. See ATTRIBUTION.txt.

Voice: assets/voice/Polivoks-by-Hans-Volt-fx.wav (44.1 kHz mono s16, sha256 83382073...):
Hans Volt's own recording of "Polivoks by Hans Volt." (iPhone Voice Memo, 24 November 2026),
resampled to 44.1 kHz mono s16. Not offered under GPL-3.0 (see ATTRIBUTION.txt).
Steps (all integer-exact or deterministic float, pure Python):
  1. trim: first/last sample above -50 dBFS, 20 ms before / 60 ms after kept
  2. resample 44.1 kHz -> 16 kHz: windowed-sinc (Blackman, 96 taps a side, cut 7.8 kHz). 16 kHz
     (Nyquist 8 kHz) keeps the spoken band; 11.025 kHz would cut 5.5-7.5 kHz (the "s" and "ts" of the line).
  3. normalise the peak to PEAK (Q15), 5 ms raised-cosine fade in and out, 4 ms of digital zero after
  4. IMA-ADPCM (the standard step and index tables), encoded by a beam search (32 decoder states) with the
     decoder in the loop, start state 0/0, two samples a byte, low nibble first. The firmware decoder (poli_boot.c boot_adpcm) is the same arithmetic.
"""
import math
import struct
import sys
import wave
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
LOGO_PNG = ROOT / "assets" / "logo" / "hv_splash_b.png"
VOICE_WAV = ROOT / "assets" / "voice" / "Polivoks-by-Hans-Volt-fx.wav"
OUT_LOGO = ROOT / "firmware" / "src" / "poli_boot_logo.h"
OUT_VOICE = ROOT / "firmware" / "src" / "poli_boot_voice.h"
LOGO_W, LOGO_H = 240, 188
RATE_IN, RATE = 44100, 16000
PEAK = 16384                     # -6 dBFS of Q15: the synth's own peaks stay near 12,600 of 30,000 (EnvRC R5)
FADE_MS, TAIL_ZERO_MS = 5, 4
PRE_MS, POST_MS, THRESH = 20, 60, 32768 * 10 ** (-50 / 20)

STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88,
        97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658,
        724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660,
        4026, 4428, 4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818,
        18500, 20350, 22385, 24623, 27086, 29794, 32767]
IDX = [-1, -1, -1, -1, 2, 4, 6, 8]

GPL_NOT = ("/* NOT GPL. The HV logo below is (C) Hans Volt (HanzVolt), all rights reserved. It is not licensed under\n"
           " * GPL-3.0 and the GPL grants no right to it (ATTRIBUTION.txt). Included with Hans's permission for the\n"
           " * Polivoks FM-1 firmware. To build without it, remove POLI_BOOT_SCREEN or replace this file. */\n")


def rgb565(c):
    r, g, b = c
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def rle_of(px):
    rle = bytearray()
    i = 0
    while i < len(px):
        j = i
        while j < len(px) and px[j] == px[i] and j - i < 16:
            j += 1
        rle.append(((j - i - 1) << 4) | px[i])
        i = j
    return rle


def logo_header():
    im = Image.open(LOGO_PNG)
    if im.mode != "P" or im.size != (LOGO_W, LOGO_H):
        sys.exit(f"{LOGO_PNG}: want a {LOGO_W}x{LOGO_H} indexed picture")
    px = list(im.tobytes())
    if max(px) > 15:
        sys.exit(f"{LOGO_PNG}: more than 16 colours")
    p8 = (im.getpalette() + [0] * 48)[:48]
    pal = [rgb565(tuple(p8[3 * k:3 * k + 3])) for k in range(16)]
    rle = rle_of(px)
    L = ["/* generated by tools/gen_poli_boot.py from assets/logo/hv_splash_b.png: the FORM / HanzVolt HV boot splash (B) */",
         GPL_NOT.rstrip("\n"), "#pragma once", "#include <stdint.h>",
         f"#define POLI_LOGO_W {LOGO_W}", f"#define POLI_LOGO_H {LOGO_H}",
         "static const uint16_t POLI_LOGO_PAL[16] = {" + ", ".join(f"0x{v:04X}" for v in pal) + "};",
         f"static const uint8_t POLI_LOGO_RLE[{len(rle)}] = {{"]
    for k in range(0, len(rle), 24):
        L.append("    " + ", ".join(str(b) for b in rle[k:k + 24]) + ",")
    L.append("};")
    return "\n".join(L) + "\n", len(rle)


def read_wav():
    with wave.open(str(VOICE_WAV)) as w:
        if w.getnchannels() != 1 or w.getsampwidth() != 2 or w.getframerate() != RATE_IN:
            sys.exit(f"{VOICE_WAV}: want 44.1 kHz mono s16")
        raw = w.readframes(w.getnframes())
    return list(struct.unpack("<%dh" % (len(raw) // 2), raw))


def resample(x):
    """44.1 -> 16 kHz windowed sinc, deterministic"""
    half, fc = 96, 7800.0 / RATE_IN               # cut in cycles per input sample
    n_out = int(len(x) * RATE / RATE_IN)
    y = []
    for n in range(n_out):
        t = n * RATE_IN / RATE
        k0 = int(math.floor(t))
        acc = wsum = 0.0
        for k in range(k0 - half + 1, k0 + half + 1):
            d = t - k
            if abs(d) >= half:
                continue
            s = 2 * fc if d == 0 else math.sin(2 * math.pi * fc * d) / (math.pi * d)
            wv = 0.42 + 0.5 * math.cos(math.pi * d / half) + 0.08 * math.cos(2 * math.pi * d / half)
            h = s * wv
            wsum += h
            if 0 <= k < len(x):
                acc += x[k] * h
        y.append(acc / wsum)
    return y


def voice_pcm16k():
    x = read_wav()
    above = [i for i, v in enumerate(x) if abs(v) > THRESH]
    a = max(0, above[0] - RATE_IN * PRE_MS // 1000)
    b = min(len(x), above[-1] + 1 + RATE_IN * POST_MS // 1000)
    y = resample(x[a:b])
    pk = max(abs(v) for v in y)
    g = PEAK / pk
    nf = RATE * FADE_MS // 1000
    out = []
    for i, v in enumerate(y):
        f = 1.0
        if i < nf:
            f = 0.5 - 0.5 * math.cos(math.pi * i / nf)
        elif i >= len(y) - nf:
            f = 0.5 - 0.5 * math.cos(math.pi * (len(y) - 1 - i) / nf)
        out.append(int(round(v * g * f)))
    out[0] = 0
    out[-1] = 0
    out += [0] * (RATE * TAIL_ZERO_MS // 1000)
    if len(out) % 2:
        out.append(0)
    info = dict(src_frames=len(x), trim_a=a, trim_b=b, peak_src=max(abs(v) for v in x[a:b]), peak_rs=pk, gain=g)
    return out, info


def ima_step(code, pred, idx):
    st = STEP[idx]
    d = st >> 3
    if code & 4: d += st
    if code & 2: d += st >> 1
    if code & 1: d += st >> 2
    pred = pred - d if code & 8 else pred + d
    pred = max(-32768, min(32767, pred))
    idx = max(0, min(88, idx + IDX[code & 7]))
    return pred, idx


def ima_encode(pcm, beam=32):
    """standard IMA-ADPCM bit stream chosen by a beam search (the BEAM best decoder states by summed squared error,
    merged on equal (predictor, index)); any IMA decoder plays it. Deterministic (ties: tuple order)."""
    beams = [(0, 0, 0, None)]
    for s in pcm:
        cand = {}
        for cost, pred, idx, hist in beams:
            for c in range(16):
                p, ix = ima_step(c, pred, idx)
                nc = cost + (s - p) * (s - p)
                k = (p, ix)
                if k not in cand or cand[k][0] > nc:
                    cand[k] = (nc, p, ix, (c, hist))
        beams = sorted(cand.values(), key=lambda t: (t[0], t[1], t[2]))[:beam]
    codes, h = [], beams[0][3]
    while h:
        codes.append(h[0])
        h = h[1]
    codes.reverse()
    data = bytearray()
    for i in range(0, len(codes), 2):
        data.append(codes[i] | (codes[i + 1] << 4))
    return data


def ima_decode(data, n):
    pred = idx = 0
    out = []
    for i in range(n):
        c = (data[i >> 1] >> ((i & 1) * 4)) & 15
        pred, idx = ima_step(c, pred, idx)
        out.append(pred)
    return out


def voice_header():
    pcm, info = voice_pcm16k()
    data = ima_encode(pcm)
    dec = ima_decode(data, len(pcm))
    err = [d - s for d, s in zip(dec, pcm)]
    rms_e = math.sqrt(sum(e * e for e in err) / len(err))
    rms_s = math.sqrt(sum(s * s for s in pcm) / len(pcm))
    L = ["/* generated by tools/gen_poli_boot.py from assets/voice/Polivoks-by-Hans-Volt-fx.wav: the load screen voice",
         " * \"Polivoks by Hans Volt\" (Hans Volt's own recording, 24 November 2026). Not offered under GPL-3.0,",
         " * see ATTRIBUTION.txt.",
         f" * 16 kHz mono IMA-ADPCM (beam-search encoded), {len(pcm)} samples ({len(pcm) / RATE:.6f} s), {len(data)} B, start state 0/0,",
         f" * low nibble first. Source trim {info['trim_a']}..{info['trim_b']} of {info['src_frames']} (44.1 kHz).",
         f" * Peak {PEAK} (Q15), 5 ms fades. Decoded vs encoder input: max |err| {max(abs(e) for e in err)},"
         f" SNR {20 * math.log10(rms_s / rms_e):.2f} dB. */",
         "#pragma once", "#include <stdint.h>",
         f"#define POLI_VOICE_RATE {RATE}u", f"#define POLI_VOICE_N {len(pcm)}u",
         f"static const uint8_t POLI_VOICE_ADPCM[{len(data)}] = {{"]
    for k in range(0, len(data), 24):
        L.append("    " + ", ".join(str(b) for b in data[k:k + 24]) + ",")
    L.append("};")
    stats = dict(info, n=len(pcm), bytes=len(data), maxerr=max(abs(e) for e in err),
                 snr=20 * math.log10(rms_s / rms_e), pcm=pcm, dec=dec)
    return "\n".join(L) + "\n", stats


def write_wav(path, s, rate):
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(rate)
        w.writeframes(struct.pack("<%dh" % len(s), *s))


def main():
    a = sys.argv[1:]
    lh, nlogo = logo_header()
    vh, st = voice_header()
    if a and a[0] == "--wav":
        write_wav(a[1], st["dec"], RATE)
        write_wav(a[1].replace(".wav", "-encoder-input.wav"), st["pcm"], RATE)
        print(f"wav: {a[1]} ({st['n']} samples at {RATE})")
        return
    if a and a[0] == "--check":
        ok = OUT_LOGO.read_text() == lh and OUT_VOICE.read_text() == vh
        print("gen_poli_boot: check", "OK" if ok else "DIFFERS")
        sys.exit(0 if ok else 1)
    OUT_LOGO.write_text(lh)
    OUT_VOICE.write_text(vh)
    print(f"logo: {LOGO_W}x{LOGO_H}, {nlogo} B RLE + 32 B palette -> {OUT_LOGO}")
    print(f"voice: {st['n']} samples ({st['n'] / RATE:.6f} s) at {RATE} Hz, {st['bytes']} B IMA-ADPCM, "
          f"max err {st['maxerr']}, SNR {st['snr']:.2f} dB, trim {st['trim_a']}..{st['trim_b']}, "
          f"src peak {st['peak_src']}, gain {st['gain']:.4f} -> {OUT_VOICE}")


if __name__ == "__main__":
    main()
