#!/usr/bin/env python3
"""P-Vox title bitmap for the window header, hand-drawn in the style of the
Formanta Polivoks panel logo (ПОЛИВОКС). 1-bit, no anti-aliasing.

  tools/gen_poli_pvox_logo.py           -> firmware/src/poli_pvox_logo.inc
  tools/gen_poli_pvox_logo.py --check   exit 1 if the include is stale
  tools/gen_poli_pvox_logo.py --png F   also write a 1x PNG of the bitmap (needs Pillow)

Proportions measured off a photo of the panel logo (letter ~90 px tall,
~119 px wide, horizontal bars ~23 px, stems ~25 px, outer corner radius ~20 px)
and fitted to the exact cell of the Terminus Bold 20 POLIVOKS wordmark it
replaces (80 px wide, 18 rows, caps on rows 3..15), so the title neither grows
nor moves: letters 16x13 (1.23x wider than tall; the logo's 1.32x would need
85 px), bars 3 rows, stems 4 columns, outer corners cut 2/1 px, slot counters,
3-px gaps between letters (one bar stroke),
2 px either side of the hyphen. The logo has no Latin letters; P, V, X and the
hyphen are drawn to match:
  P  = the logo's В/П construction: rounded top corners, flat stem foot, 8x3
       slot counter, the bowl closing at row 8 with the same corner cut as О
  -  = one horizontal bar of the logo (3 rows), 6 px long, on the bars' centre line
  V  = straight 4-px stems like И/Л, then diagonals meeting in a flat foot
  O  = the logo's О (rounded rectangle, 8x7 counter)
  X  = two of К's arms (5-px diagonals, flat-cut ends), crossed
The letters are drawn upright: the photo's ~5 degree slant is 1 px at this size.
The same bitmap is used in English and Russian mode: a Russian П-ВОКС in this
style needs five letters plus the hyphen, which only fits 80 px with 13-px
square letters (no longer the logo's wide shape).
"""
