GAPS = [2, 2, 3, 3]   # P-  -V  VO  OX: 3 px (one bar stroke) between letters, 2 px around the hyphen
GLYPHS = [P, HY, V, O, X]


def rows_of(g):
    r = [l for l in g.strip("\n").split("\n")]
    assert len(r) == 13 and len({len(l) for l in r}) == 1, g
    return r


def bitmap():
    gl = [rows_of(g) for g in GLYPHS]
    out = []
    for y in range(13):
        r = gl[0][y]
        for g, gp in zip(gl[1:], GAPS):
            r += "." * gp + g[y]
        out.append(r)
    return out


def render():
    bm = bitmap()
    W, H = len(bm[0]), len(bm)
    nb = (W + 7) // 8
    o = ["/* generated by tools/gen_poli_pvox_logo.py - do not edit.",
         " * P-Vox title, hand-drawn after the Formanta Polivoks panel logo (ПОЛИВОКС);",
         " * 1 bit per pixel, MSB = leftmost, rows top to bottom. */",
         f"#define PVOX_W {W}", f"#define PVOX_H {H}", f"#define PVOX_NB {nb}",
         f"#define PVOX_Y0 3   /* first ink row inside the 18-row wordmark cell (Terminus caps: rows 3..15) */",
         f"static const uint8_t PVOX_BITS[PVOX_H][PVOX_NB] = {{"]
    for r in bm:
        bits = r.ljust(nb * 8, ".")
        by = [int(bits[i:i + 8].replace("#", "1").replace(".", "0"), 2) for i in range(0, nb * 8, 8)]
        o.append("    {" + ",".join(f"0x{b:02x}" for b in by) + "}, /* " + r.replace(".", " ").rstrip() + " */")
    o.append("};")
    o.append(f"/* table bytes: {H * nb} */")
    return "\n".join(o) + "\n", bm


def main():
    text, bm = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("poli_pvox_logo.inc", "up to date" if ok else "STALE")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print(f"P-Vox {len(bm[0])}x{len(bm)} -> {OUT.relative_to(ROOT)}")
    if "--png" in sys.argv:
        from PIL import Image
        f = sys.argv[sys.argv.index("--png") + 1]
        im = Image.new("1", (len(bm[0]), len(bm)))
        for y, r in enumerate(bm):
            for x, c in enumerate(r):
                im.putpixel((x, y), c == "#")
        im.save(f)


if __name__ == "__main__":
    main()
