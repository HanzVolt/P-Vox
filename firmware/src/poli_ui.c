    if (ch) hline(tx, y + (trh - th(E_PT)) / 2 + th(E_PT) / 2, g_tw(xtra_title(w), E_PT), COL_SOOT);   /* stencil break */
    if (w == 5) { sa = tr("FREE", "СВОБ."); sb = tr("LOCK", "ЗАМОК"); sw = seg_w(sa, sb, 40); }
    if (w == 10) { sb = tr("KEYS", "КЛАВ."); sw = seg_w(sa, sb, 40); }
