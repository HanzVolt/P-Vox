static const char *tr(const char *en, const char *ru) { return poli_nav_lang() ? ru : en; }

static uint32_t next_cp(const char **ps)
{
    const uint8_t *s = (const uint8_t *)*ps;
    uint32_t c;
    if (!s || !s[0]) return 0;
    if (s[0] < 0x80u) { *ps += 1; return s[0]; }
    if ((s[0] & 0xE0u) == 0xC0u && s[1]) {
        c = ((uint32_t)(s[0] & 0x1Fu) << 6) | (s[1] & 0x3Fu);
        *ps += 2;
        return c;
    }
    *ps += 1;
    return (uint32_t)'?';
}

static int glyph_at(int f, uint32_t cp)
{
    int i;
    if (f == F_TN) {
        for (i = 0; i < TN_N; i++)
            if (TN_CP[i] == cp) return i;
        return -1;
    }
    if (f == F_T20) {
        for (i = 0; i < TB20_N; i++)
            if (TB20_CP[i] == cp) return i;
        return -1;
    }
    for (i = 0; i < GUI_N; i++)
        if (GUI_CP[i] == cp) return i;
    return -1;
}

static int f_w(int f) { return f == F_T20 ? TB20_W : f == F_T16 ? TB16_W : f == F_TN ? TN_W : 6; }
static int f_h(int f) { return f == F_T20 ? TB20_H : f == F_T16 ? TB16_H : f == F_TN ? TN_H : 7; }
static int f_ink(int f) { return f == F_T20 ? TB20_W : f == F_T16 ? TB16_W : f == F_TN ? TN_W : 5; }
static unsigned f_row(int f, int gi, int r)
{
    if (f == F_TN) return TN_BITS[gi][r];
    if (f == F_T16) return TB16_BITS[gi][r];
    if (f == F_T20) return TB20_BITS[gi][r];
    return (unsigned)GUI_GLYPH[gi][r] << 1;   /* 5 bits -> 6-wide cell, MSB left */
}
static int adv(int e) { const sty_t *s = &STY[e]; return f_w(s->f) * s->sc + s->bold; }
static int th(int e) { return f_h(STY[e].f) * STY[e].sc; }

static int g_tw(const char *s, int e)
{
    const sty_t *st = &STY[e];
    int n = 0;
    while (s && *s) { if (!next_cp(&s)) break; n++; }
    return n ? (n - 1) * adv(e) + f_ink(st->f) * st->sc + st->bold : 0;
}

static void g_text(int x, int y, const char *s, int e, uint16_t c)
{
    const sty_t *st = &STY[e];
    int sc = st->sc, w = f_w(st->f), h = f_h(st->f), a = adv(e);
    int sx, sy, col, row;
#ifdef POLI_UI_PROBE
    probe_text(x, y, g_tw(s, e), th(e), e, s);
#endif
    while (s && *s) {
        uint32_t cp = next_cp(&s);
        int gi;
        if (!cp) break;
        gi = glyph_at(st->f, cp);
        for (row = 0; row < h; row++) {
            unsigned mask = gi >= 0 ? f_row(st->f, gi, row) : (row == 0 || row == h - 1 ? 0xFFFFu : 0x8001u);
            for (col = 0; col < w; col++) {
                if (mask & (1u << (w - 1 - col))) {
                    for (sy = 0; sy < sc; sy++)
                        for (sx = 0; sx < sc + st->bold; sx++)
                            PSET(x + col * sc + sx, y + row * sc + sy, c);
                }
            }
        }
        x += a;
    }
}
static void g_text_c(int cx, int y, const char *s, int e, uint16_t c) { g_text(cx - g_tw(s, e) / 2, y, s, e, c); }
static void g_text_r(int rx, int y, const char *s, int e, uint16_t c) { g_text(rx - g_tw(s, e), y, s, e, c); }

_Static_assert(PVOX_Y0 + PVOX_H <= TB20_H, "P-Vox title overflows the wordmark cell");
/* P-Vox title: PVOX_W x PVOX_H, 1 bit per pixel, at (x, y + PVOX_Y0) inside an
 * 18-row wordmark cell whose top-left is (x, y) */
static void title_logo(int x, int y, uint16_t c)
{
    int r, col;
#ifdef POLI_UI_PROBE
    probe_text(x, y, PVOX_W, th(E_MARK), E_MARK, "P-Vox");
#endif
    for (r = 0; r < PVOX_H; r++)
        for (col = 0; col < PVOX_W; col++)
            if (PVOX_BITS[r][col >> 3] & (0x80u >> (col & 7))) PSET(x + col, y + PVOX_Y0 + r, c);
}

static void hline(int x, int y, int w, uint16_t c) { int i; for (i = 0; i < w; i++) PSET(x + i, y, c); }
static void vline(int x, int y, int h, uint16_t c) { int i; for (i = 0; i < h; i++) PSET(x, y + i, c); }
static void fill_rect(int x, int y, int w, int h, uint16_t c)
{
    int r, col;
    if (w <= 0 || h <= 0) return;
    for (r = 0; r < h; r++)
        for (col = 0; col < w; col++)
            PSET(x + col, y + r, c);
}
static void box(int x, int y, int w, int h, uint16_t c)
{
    if (w < 2 || h < 2) return;
    hline(x, y, w, c); hline(x, y + h - 1, w, c);
    vline(x, y, h, c); vline(x + w - 1, y, h, c);
}
static void line(int x0, int y0, int x1, int y1, uint16_t c)
{
    int dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1;
    int dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1;
    int err = dx + dy, guard = 400;
    while (guard--) {
        int e2 = 2 * err;
        PSET(x0, y0, c);
        if (x0 == x1 && y0 == y1) break;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}
static void circle(int cx, int cy, int r, uint16_t c)
{
    int x = r, y = 0, e = 1 - r;
    if (r < 1) return;
    while (x >= y) {
        PSET(cx + x, cy + y, c); PSET(cx + y, cy + x, c);
        PSET(cx - x, cy + y, c); PSET(cx - y, cy + x, c);
        PSET(cx + x, cy - y, c); PSET(cx + y, cy - x, c);
        PSET(cx - x, cy - y, c); PSET(cx - y, cy - x, c);
        y++;
        if (e < 0) e += 2 * y + 1; else { x--; e += 2 * (y - x) + 1; }
    }
}
static void knob(int cx, int cy, int r, int pos, int lo, int hi, uint16_t rim, uint16_t ptr)
{
    int t, idx, i;
    OBST(cx - r - 5, cy - r - 5, 2 * r + 11, 2 * r + 11, "knob");
    circle(cx, cy, r, rim);
    if (r > 4) circle(cx, cy, r - 2, rim);
    for (i = 0; i < 32; i += 4)
        line(cx + DIRX[i] * (r + 2) / 16, cy + DIRY[i] * (r + 2) / 16,
             cx + DIRX[i] * (r + 5) / 16, cy + DIRY[i] * (r + 5) / 16, COL_DIM);
    if (hi <= lo) t = 0;
    else { if (pos < lo) pos = lo; if (pos > hi) pos = hi; t = (pos - lo) * 24 / (hi - lo); }
    idx = (20 + t) & 31;
    line(cx, cy, cx + DIRX[idx] * (r - 4) / 16, cy + DIRY[idx] * (r - 4) / 16, ptr);
    line(cx + 1, cy, cx + 1 + DIRX[idx] * (r - 5) / 16, cy + DIRY[idx] * (r - 5) / 16, ptr);
    PSET(cx, cy, ptr);
}
static void bar(int x, int y, int w, int h, int pos, int maxv)
{
    int fill, inner;
    OBST(x, y, w, h, w < 60 ? "bar<60px" : "bar");
    if (maxv < 1) maxv = 1;
    if (pos < 0) pos = 0;
    if (pos > maxv) pos = maxv;
    box(x, y, w, h, COL_GRAY);
    inner = w - 4;
    fill = inner * pos / maxv;
    if (fill > 0) fill_rect(x + 2, y + 2, fill, h - 4, COL_OR);
}
static int seg_h(void) { int h = th(E_SEG) + (STY[E_SEG].f == F_57 ? 7 : 4); return h < 16 ? 16 : h; }
static int seg_w(const char *a, const char *b, int minw)
{
    int w = g_tw(a, E_SEG), w2 = g_tw(b, E_SEG);
    if (w2 > w) w = w2;
    w += 14;
    return w < minw ? minw : w;
}
static void segment(int x, int y, int w, int h, int on, const char *label)
{
    uint16_t fg = on ? COL_INK : COL_GRAY;
    if (on) fill_rect(x, y, w, h, COL_OR); else box(x, y, w, h, COL_GRAY);
    CONT(x + 1, y + 1, w - 2, h - 2);
    g_text_c(x + w / 2, y + (h - th(E_SEG)) / 2, label, E_SEG, fg);
}
