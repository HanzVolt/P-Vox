static void put_i(char *d, int v)
{
    char tmp[8];
    int i = 0;
    unsigned u;
    if (v < 0) { *d++ = '-'; u = (unsigned)(-v); } else u = (unsigned)v;
    do { tmp[i++] = (char)('0' + (u % 10u)); u /= 10u; } while (u && i < 7);
    while (i) *d++ = tmp[--i];
    *d = 0;
}
