/* ---- BLOCK TIMER test build (14 Nov 2026). The audio ISR's figures (platform.c, struct bt) in place of the
 * grey FM-1 tag on the preset row: "1273US 22% L0" = the longest half fill since the reset in microseconds
 * (TIMER4 wall time, TIMER5 nested in it included: what the 5805 us deadline sees), that as % of 5805 us,
 * and how many halves came late (the DMA moved on during the fill). Orange once anything came late.
 * Where the preset row leaves less room: "1273 22% L0", "22% L0", then "L5" (or "22%" while none came
 * late). OCT- + OCT+ together resets the max and the late count (the octave reset, as before). The main loop repaints the preset row (rows
 * 22..36) when the figures change, at most 4 times a second. Host frames: no audio ISR runs, nothing is
 * measured, the readout shows zeros. */
#ifndef POLI_BT
#define BT_DEADLINE_US 5805u
static struct { uint32_t max_all, max_render, late; } bt;
static void bt_reset(void) { bt.max_all = 0; bt.max_render = 0; bt.late = 0; }
#endif
#ifndef FM1_TICKS_PER_US
#define FM1_TICKS_PER_US 24u
#endif
static uint32_t bt_shown_us = 0xFFFFFFFFu, bt_shown_late;
static void bt_put(char **d, const char *s) { while (*s) *(*d)++ = *s++; }
static void bt_num(char **d, uint32_t v, uint32_t cap) { char t[12]; put_i(t, (int)(v > cap ? cap : v)); bt_put(d, t); }
/* form f of the readout: 0 "1273US 22% L0", 1 "1273 22% L0", 2 "22% L0", 3 "L5" once late, else "22%" (fits the
 * narrowest room: a 12-letter edited name and a "12/12" roll tag leave 49 px, 7 cells). Capped: 99999 us, 999 %,
 * 9999 late */
static void bt_form(char *d, int f, uint32_t us, uint32_t pct, uint32_t late)
{
    if (f < 2) { bt_num(&d, us, 99999u); bt_put(&d, f == 0 ? "US " : " "); }
    if (f < 3 || !late) { bt_num(&d, pct, 999u); bt_put(&d, "%"); }
    if (f < 3) bt_put(&d, " ");
    if (f < 3 || late) { bt_put(&d, "L"); bt_num(&d, late, 9999u); }
    *d = 0;
}
static void bt_draw(int rx, int ty, int left)
{
    uint32_t us = bt.max_all / FM1_TICKS_PER_US, late = bt.late;
    uint32_t pct;
    if (us > 99999u) us = 99999u;               /* (no overflow below; shown capped anyway) */
    pct = (us * 100u + BT_DEADLINE_US / 2u) / BT_DEADLINE_US;
    char s[28];
    int f = 0;
    for (;;) {
        bt_form(s, f, us, pct, late);
        if (f == 3 || g_tw(s, E_SUB) <= rx - left) break;
        f++;
    }
    g_text_r(rx, ty, s, E_SUB, late ? COL_OR : COL_GRAY);
    bt_shown_us = bt.max_all / FM1_TICKS_PER_US;
    bt_shown_late = late;
}
int poli_ui_bt_stale(void) { return bt.max_all / FM1_TICKS_PER_US != bt_shown_us || bt.late != bt_shown_late; }

