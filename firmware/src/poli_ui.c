static const char *const SYNC_NAME[10] = { "", "1/1", "1/2", "1/4", "1/4T", "1/8", "1/8T", "1/16", "1/16T", "1/32" };
/* named values (LFO restart, LFO sync, velocity off); 0 = a number */
static const char *slot_str(int kind, int p)
{
    if (kind == SLOT_LFO_RST) return p ? tr("ON", "ВКЛ") : tr("OFF", "ВЫКЛ");
    if (kind == SLOT_LFO_SYNC) return (p <= 0 || p > 9) ? tr("FREE", "СВОБ.") : SYNC_NAME[p];
    if (kind == SLOT_VEL && p == 0) return tr("OFF", "ВЫКЛ");
    return 0;
}
static void slot_text(char *b, int kind, int p)
{
    b[0] = 0;
    if (kind == SLOT_EMPTY) return;
    if (kind == SLOT_EXT) { b[0] = '-'; b[1] = '-'; b[2] = 0; return; }
    if (kind == SLOT_FOOT1 || kind == SLOT_FOOT2) {
        const char *s = foot_name(p);
        int i = 0;
        while (s[i] && i < 6) { b[i] = s[i]; i++; }
        b[i] = 0;
        return;
    }
    if (kind == SLOT_DUO) { b[0] = p ? '2' : '1'; b[1] = 0; return; }
    put_i(b, p);
}
