static int knob_block(int r) { return 2 * r + 11 + 2 + th(E_LAB) + 1 + th(E_VAL); }
static void one_knob(int cx, int cy, int r, const char *lab, const char *val, int pos, int lo, int hi, int hot)
{
    knob(cx, cy, r, pos, lo, hi, hot ? COL_GRAY : COL_DIM, hot ? COL_CREAM : COL_GRAY);
    g_text_c(cx, cy + r + 7, lab, E_LAB, hot ? COL_GRAY : COL_DIM);
    if (val && val[0]) g_text_c(cx, cy + r + 8 + th(E_LAB), val, E_VAL, hot ? COL_CREAM : COL_GRAY);
}
static void gen_panel(int x, int y, int w, int h, int hot, const char *title, int range, int shape,
                      int third_pos, int third_known, const char *third_lab, int mod_pos,
                      const char *mod_lab, int show_waves, int link_slot, int link)
{
    char a[8], b[8];
    int ty = y + 4, top = ty + th(E_PT) + 4;
    int avail = y + h - 3 - top;
    int r = 14, cy0, cy1, det = third_lab == tr("DETUNE", "РАССТР.");
    int tcx = x + w / 2;
    while (r > 8 && 2 * knob_block(r) > avail) r--;
    cy0 = top + r + 5;
    cy1 = cy0 + knob_block(r);
    panel(x, y, w, h, hot);
    if (link_slot) {
        /* Title and the LINK marker share the title row. The room is kept
           whether or not the link is on, so the title never moves. */
        const char *mk = tr("LINK", "СВЯЗЬ");
        int tw = g_tw(title, E_PT), mw = g_tw(mk, E_LAB), gx = x + w / 2 - (tw + 8 + mw) / 2;
        tcx = gx + tw / 2;
        if (link) g_text(gx + tw + 8, ty, mk, E_LAB, COL_OR);
    }
    g_text_c(tcx, ty, title, E_PT, hot ? COL_CREAM : COL_GRAY);
    slot_text(a, SLOT_FOOT1, range);
    one_knob(x + 30, cy0, r, tr("RANGE", "ДИАП."), a, range, -2, 2, hot);
    one_knob(x + w - 30, cy0, r, tr("WAVE", "ФОРМА"), "", shape, 0, 4, hot);
    if (show_waves) wave_row(x + w - 54, cy0 + r + 8 + th(E_LAB) + (th(E_VAL) - 7) / 2, shape);
    if (third_known) {
        put_i(b, third_pos);
        one_knob(x + 30, cy1, r, third_lab, b, third_pos, det ? -64 : 0, det ? 64 : 127, hot);
    } else one_knob(x + 30, cy1, r, third_lab, "--", 0, 0, 127, 0);
    put_i(b, mod_pos);
    one_knob(x + w - 30, cy1, r, mod_lab, b, mod_pos, 0, 127, hot);
}

