/* the status line: the clock for ARP / SEQ / DRUMS, core 2 for the sound features */
static void xtra_status(const poli_nav_view_t *v, char *d)
{
    char n[12];
    d[0] = 0;
    if (v->xtra <= 2 || v->xtra >= 5) {
        put_i(n, xtra_bpm());
        cat(d, xtra_ext() ? "MIDI " : tr("INT ", "ВНУТР. "), n);
        cat(d, d, tr(" BPM ", " УД "));
        cat(d, d, xtra_running() ? tr("PLAY", "ИГРА") : tr("STOP", "СТОП"));
        if (v->xtra == 1 && xtra_rec()) { cat(d, d, tr(" REC ", " ЗАП "));
                                          put_i(n, xtra_rec_cur() + 1); cat(d, d, n); }
        if (v->xtra == 1 && xtra_transpose()) {   /* Drums12-Transpose: "TR +5", "TR -7" */
            n[0] = xtra_transpose() > 0 ? '+' : 0; n[1] = 0;
            cat(d, d, " TR "); cat(d, d, n); put_i(n, xtra_transpose()); cat(d, d, n);
        }
        if (v->xtra != 2) return;
        cat(d, d, "  ");
    }
    if (xtra_c2() != 3) {
        cat(d, d, tr("CORE 2 OFF", "ЯДРО 2 НЕТ"));
        return;
    }
    {   /* "CORE 2 812US 14% L0": the longest job since the reset (TIMER4), as % of the 5805 us half, halves late */
        uint32_t us = xf_st.busy_max / FM1_TICKS_PER_US;
        if (us > 99999u) us = 99999u;
        cat(d, d, v->xtra == 2 ? tr("C2 ", "Я2 ") : tr("CORE 2 ", "ЯДРО 2 "));
        if (v->xtra != 2) { put_i(n, (int)us); cat(d, d, n); cat(d, d, tr("US ", "МКС ")); }
        put_i(n, (int)((us * 100u + BT_DEADLINE_US / 2u) / BT_DEADLINE_US)); cat(d, d, n); cat(d, d, "% L");
        put_i(n, (int)(xtra_c2_late() > 9999u ? 9999u : xtra_c2_late())); cat(d, d, n);
    }
}
