/* ---- Drift-Full (17 Nov 2026): the "Chernobyl" skin, on the DRUM pages only (DRUMS, GENERATE, DRUM DRIFT, GROOVE,
 * DRUM FX, PERFORM): a soot-black panel with yellow / black hazard stripes top and bottom, a radiation trefoil by the
 * title, the title in hazard yellow with a stencil break through it, yellow labels and bars, and a DP-5 style
 * dosimeter: a green counter of the Drift's mutations and a 16-cell dose bar that fills toward the next Drift
 * change. The synth's pages (ARP, WANDER, SEQ, DELAY, REVERB) are drawn exactly as before. */
static const uint16_t TREFOIL[15] = { 0x03E0, 0x07F0, 0x03E0, 0x03E0, 0x01C0, 0x0000, 0x01C0, 0x7DDF, 0x7DDF, 0x7E3F,
                                      0x3E3E, 0x3C1E, 0x1C1C, 0x0808, 0x0000 };
static int chern_page(int w) { return w == 2 || (w >= 6 && w <= 10); }
static void hazard(int x, int y, int w, int h)
{
    int i, j;
    OBST(x, y, w, h, "hazard");
    for (j = 0; j < h; j++)
        for (i = 0; i < w; i++) PSET(x + i, y + j, (((i + j) >> 2) & 1) ? COL_HZK : COL_HZY);
}
static void trefoil(int x, int y)
{
    int r, c;
    OBST(x, y, 17, 17, "trefoil");
    for (r = 0; r < 17; r++)                     /* a yellow disc, the black trefoil on it */
        for (c = 0; c < 17; c++) {
            int dx = c - 8, dy = r - 8;
            if (dx * dx + dy * dy <= 72) PSET(x + c, y + r, COL_HZY);
        }
    for (r = 0; r < 15; r++)
        for (c = 0; c < 15; c++)
            if (TREFOIL[r] & (1u << (14 - c))) PSET(x + 1 + c, y + 1 + r, COL_HZK);
}
static void bar_c(int x, int y, int w, int h, int pos, int maxv, uint16_t rim, uint16_t fc)
{
    int fill, inner;
    OBST(x, y, w, h, w < 60 ? "bar<60px" : "bar");
    if (maxv < 1) maxv = 1;
    if (pos < 0) pos = 0;
    if (pos > maxv) pos = maxv;
    box(x, y, w, h, rim);
    inner = w - 4;
    fill = inner * pos / maxv;
    if (fill > 0) fill_rect(x + 2, y + 2, fill, h - 4, fc);
}
/* the dosimeter: "ДП-5" then a 3-digit counter (mutations + surprises), green on black */
