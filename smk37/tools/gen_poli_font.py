"""Sparse Polivoks UI font. Roboto Condensed (Apache-2.0), glyphs used by poli_ui.c.

  tools/gen_poli_font.py           -> firmware/gen/poli_ui_font.h
  tools/gen_poli_font.py --check   exit 1 if the header is stale

Cyrillic is real Cyrillic from the face. This is not a Latin-1 stretch of
felucca_font.h, and it does not rewrite that header.
"""
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
TTF = ROOT / "assets" / "fonts" / "RobotoCondensed-VariableFont_wght.ttf"
UI_SRC = ROOT / "firmware" / "src" / "poli_ui.c"
OUT = ROOT / "firmware" / "gen" / "poli_ui_font.h"
PAD = 1
BASE = " 0123456789.-+'/:()?=K%+"
# One size. The FM-1 canvas strip is 64 rows; this face stays well under that.
FONTS = [("UI_F16", 16, b"SemiBold")]


def ui_chars():
    src = UI_SRC.read_text(encoding="utf-8")
    src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)
    src = re.sub(r"^\s*#\s*include.*$", "", src, flags=re.M)
    chars = set(BASE)
    for lit in re.findall(r'"((?:[^"\\\n]|\\.)*)"', src):
        chars |= set(re.sub(r"\\.", "", lit))
    return "".join(sorted(chars, key=ord))


def render(px, weight, chars):
    f = ImageFont.truetype(str(TTF), px)
    try:
        f.set_variation_by_name(weight)
    except Exception:
        f.set_variation_by_axes([600])
    asc, desc = f.getmetrics()
    h = asc + desc
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        if ord(ch) < 32:
            continue
        adv = int(round(f.getlength(ch)))
        if adv < 1 and ch != " ":
            adv = max(px // 2, 4)
        w = adv + 2 * PAD + 2
        im = Image.new("L", (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(im).text((PAD, asc), ch, font=f, fill=255, anchor="ls")
        a = [(v * 15 + 127) // 255 for v in im.tobytes()]
        cols = [x for x in range(im.size[0]) if any(a[y * im.size[0] + x] for y in range(im.size[1]))]
        bw = (max(cols) + 1) if cols else 0
        rows = []
        for y in range(h):
            r = a[y * im.size[0]:y * im.size[0] + bw]
            if bw % 2:
                r = r + [0]
            rows += [(r[i] << 4) | r[i + 1] for i in range(0, len(r), 2)]
        glyphs.append((ord(ch), adv if adv > 0 else PAD + 2, bw, rows))
    return h, glyphs


def emit():
    chars = ui_chars()
    out = [
        "/* generated by tools/gen_poli_font.py — do not edit.",
        " * Roboto Condensed (Apache-2.0), assets/fonts. Glyphs are the ones",
        " * firmware/src/poli_ui.c draws. Sparse code points, not a 32..0x04FF block.",
        " * felucca_font.h is a different ASCII face and is not produced here. */",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct {",
        "    uint8_t h, pad;",
        "    uint16_t n;",
        "    const uint16_t *cp;",
        "    const uint8_t *adv, *bw;",
        "    const uint16_t *off;",
        "    const uint8_t *data;",
        "} ui_font_t;",
        "",
    ]
    total = 0
    for name, px, weight in FONTS:
        h, gl = render(px, weight, chars)
        data, off = [], []
        for _, _, _, rows in gl:
            off.append(len(data))
            data += rows
        if len(data) > 65535:
            raise SystemExit(f"{name}: bitmap does not fit 16-bit offsets")
        n = len(gl)
        size = len(data) + n * (2 + 1 + 1 + 2) + 16
        total += size
        out.append(f"/* {name}: {px}px {weight.decode()} {n} glyphs h {h} bitmaps {len(data)} B ~{size} B */")
        out.append(f"static const uint16_t {name}_CP[{n}] = {{{', '.join(hex(g[0]) for g in gl)}}};")
        out.append(f"static const uint8_t {name}_ADV[{n}] = {{{', '.join(str(g[1]) for g in gl)}}};")
        out.append(f"static const uint8_t {name}_BW[{n}] = {{{', '.join(str(g[2]) for g in gl)}}};")
        out.append(f"static const uint16_t {name}_OFF[{n}] = {{{', '.join(map(str, off))}}};")
        out.append(f"static const uint8_t {name}_DATA[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const ui_font_t {name} = {{{h}, {PAD}, {n}, {name}_CP, {name}_ADV, {name}_BW, {name}_OFF, {name}_DATA}};")
        out.append("")
        print(f"{name}: {px}px {weight.decode()} {n} glyphs h {h} bitmaps {len(data)} B ~{size} B")
    out.append(f"/* total ~{total} B */")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print("font header up to date" if ok else "font header STALE")
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"-> {OUT.relative_to(ROOT)}  ({len(chars)} chars)")
    if "\u0410" not in chars or "\u0430" not in chars:
        print("warning: А/а missing from the UI strings")
    return 0


if __name__ == "__main__":
    sys.exit(emit())
