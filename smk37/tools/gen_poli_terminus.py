"""Terminus Bold bitmaps for the Polivoks window (scratch test copy).

  tools/gen_poli_terminus.py           -> firmware/src/poli_terminus.inc
  tools/gen_poli_terminus.py --check   exit 1 if the include is stale

Glyph bitmaps are derived from Terminus Font by Dimitar Toshkov Zhekov,
licensed under the SIL Open Font License 1.1 (assets/fonts/Terminus-LICENSE.txt,
which also covers ter-u20b.bdf from Terminus 4.49.1). The OFL text must travel
with any copy. Only bitmaps are converted; no font file is redistributed under
the reserved name.

TB16: ter-u16b.bdf (8x16 cell, rows cropped to the ink of the 74 UI code
points -> 8x14), every code point of GUI_CP in poli_gui_font.inc, same order,
so one glyph index serves both the 5x7 face and TB16.
TB20: ter-u20b.bdf (10x20 cell, cropped to 10x18), wordmark only: the letters
of "POLIVOKS" and "ПОЛИВОКС".
"""
import re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
INC = ROOT / "firmware/src/poli_gui_font.inc"
OUT = ROOT / "firmware/src/poli_terminus.inc"
U16 = ROOT / "assets/fonts/ter-u16b.bdf"
U20 = ROOT / "assets/fonts/ter-u20b.bdf"
WORDMARK = ("POLIVOKS", "ПОЛИВОКС")
NAMEF = ROOT / "firmware/src/poli_name_font.inc"
# Preset-name character set (LOCKED #3 free-form names, #12 asterisk). The order is the K2 letter order and
# also the 1-byte code stored in a preset record (0 = space). Appending at the end keeps old names valid.
NAME_CHARS = (" " + "ABCDEFGHIJKLMNOPQRSTUVWXYZ" + "abcdefghijklmnopqrstuvwxyz"
              + "АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯ" + "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
              + "0123456789" + "'+-./*!?#&():,_=")
NAME_GROUPS = (0, 1, 27, 53, 86, 119, 129)   # space, A-Z, a-z, А-Я, а-я, 0-9, marks

def parse_bdf(path):
    txt = Path(path).read_text(errors="replace")
    fbb = list(map(int, re.search(r"^FONTBOUNDINGBOX (.*)$", txt, re.M).group(1).split()))
    asc = int(re.search(r"^FONT_ASCENT (\d+)", txt, re.M).group(1))
    W, H = fbb[0], fbb[1]
    out = {}
    for m in re.finditer(r"STARTCHAR.*?ENCODING (-?\d+).*?BBX (-?\d+) (-?\d+) (-?\d+) (-?\d+).*?BITMAP\n(.*?)ENDCHAR", txt, re.S):
        enc = int(m.group(1)); bw, bh, bx, by = map(int, m.group(2, 3, 4, 5))
        rows = [int(r, 16) for r in m.group(6).split()]
        nbits = ((bw + 7) // 8) * 8
        grid = [[0] * W for _ in range(H)]
        top = asc - (by + bh)
        for i, r in enumerate(rows):
            for c in range(bw):
                if r & (1 << (nbits - 1 - c)):
                    y, x = top + i, bx + c
                    if 0 <= y < H and 0 <= x < W:
                        grid[y][x] = 1
        out[enc] = grid
    return W, H, out

def crop(W, H, gl, cps):
    sel = [gl[cp] for cp in cps]
    ink = [y for y in range(H) if any(any(g[y]) for g in sel)]
    return ink[0], ink[-1] + 1

def emit():
    inc = INC.read_text()
    cps = [int(x, 16) for x in re.findall(r"0x([0-9a-f]{4})", inc.split("GUI_CP[] = {")[1].split("}")[0])]
    assert len(cps) == int(re.search(r"#define GUI_N (\d+)", inc).group(1))
    o = ["/* generated by tools/gen_poli_terminus.py - do not edit.",
         " * Bitmaps derived from Terminus Font, (C) 2020 Dimitar Toshkov Zhekov,",
         " * SIL Open Font License 1.1: assets/fonts/Terminus-LICENSE.txt.",
         " * TB16 = ter-u16b (Terminus 4.48) for all UI text, GUI_CP order.",
         " * TB20 = ter-u20b (Terminus 4.49.1), wordmark letters only. */"]
    W, H, gl = parse_bdf(U16)
    r0, r1 = crop(W, H, gl, cps)
    assert W == 8
    o.append(f"/* TB16: cell {W}x{H}, rows {r0}..{r1-1} kept, {len(cps)} glyphs x {r1-r0} B = {len(cps)*(r1-r0)} B */")
    o.append(f"#define TB16_W {W}\n#define TB16_H {r1-r0}")
    o.append(f"static const uint8_t TB16_BITS[{len(cps)}][{r1-r0}] = {{")
    for cp in cps:
        g = gl[cp]
        vals = [sum(1 << (W - 1 - x) for x in range(W) if g[y][x]) for y in range(r0, r1)]
        o.append("    {" + ",".join(f"0x{v:02x}" for v in vals) + f"}}, /* U+{cp:04X} */")
    o.append("};")
    n16 = len(cps) * (r1 - r0)
    # wordmark: crop rows over the full UI set so it lines up with the study sheet (10x18)
    W2, H2, gl2 = parse_bdf(U20)
    q0, q1 = crop(W2, H2, gl2, cps)
    wcp = []
    for s in WORDMARK:
        for ch in s:
            if ord(ch) not in wcp: wcp.append(ord(ch))
    o.append(f"/* TB20: cell {W2}x{H2}, rows {q0}..{q1-1} kept, {len(wcp)} glyphs x {q1-q0} x 2 B = {len(wcp)*(q1-q0)*2} B"
             f" + map {len(wcp)*2} B */")
    o.append(f"#define TB20_W {W2}\n#define TB20_H {q1-q0}\n#define TB20_N {len(wcp)}")
    o.append(f"static const uint16_t TB20_CP[TB20_N] = {{{', '.join(f'0x{c:04x}' for c in wcp)}}};")
    o.append(f"static const uint16_t TB20_BITS[TB20_N][{q1-q0}] = {{")
    for cp in wcp:
        g = gl2[cp]
        vals = [sum(1 << (W2 - 1 - x) for x in range(W2) if g[y][x]) for y in range(q0, q1)]
        o.append("    {" + ",".join(f"0x{v:04x}" for v in vals) + f"}}, /* U+{cp:04X} */")
    o.append("};")
    n20 = len(wcp) * ((q1 - q0) * 2 + 2)
    o.append(f"/* table bytes: TB16 {n16} + TB20 {n20} = {n16 + n20} */")
    text = "\n".join(o) + "\n"
    # name font: ter-u16b, its own crop over the name set (descenders and the Ё/й marks kept)
    ncp = [ord(c) for c in NAME_CHARS]
    assert len(set(ncp)) == len(ncp)
    for g0 in NAME_GROUPS: assert 0 <= g0 < len(ncp)
    n0, n1 = crop(W, H, gl, ncp)
    no = ["/* generated by tools/gen_poli_terminus.py - do not edit.",
          " * Preset-name face: ter-u16b (Terminus 4.48), (C) 2020 Dimitar Toshkov Zhekov, SIL OFL 1.1",
          " * (assets/fonts/Terminus-LICENSE.txt). Index = the stored name code (0 = space). */",
          f"/* TN: cell {W}x{H}, rows {n0}..{n1-1} kept, {len(ncp)} glyphs x {n1-n0} B = {len(ncp)*(n1-n0)} B + map {len(ncp)*2} B */",
          f"#define TN_W {W}\n#define TN_H {n1-n0}\n#define TN_N {len(ncp)}",
          f"#define TN_NGROUP {len(NAME_GROUPS)}",
          "static const uint8_t TN_GROUP[TN_NGROUP] = {" + ", ".join(map(str, NAME_GROUPS)) + "};",
          "static const uint16_t TN_CP[TN_N] = {" + ",".join(f"0x{c:04x}" for c in ncp) + "};",
          f"static const uint8_t TN_BITS[TN_N][{n1-n0}] = {{"]
    for cp in ncp:
        g = gl[cp]
        vals = [sum(1 << (W - 1 - x) for x in range(W) if g[y][x]) for y in range(n0, n1)]
        no.append("    {" + ",".join(f"0x{v:02x}" for v in vals) + f"}}, /* U+{cp:04X} */")
    no.append("};")
    ntext = "\n".join(no) + "\n"
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text and NAMEF.exists() and NAMEF.read_text() == ntext
        print("terminus include up to date" if ok else "terminus include STALE")
        return 0 if ok else 1
    OUT.write_text(text)
    NAMEF.write_text(ntext)
    print(f"TN {len(ncp)*(n1-n0) + len(ncp)*2} B ({len(ncp)} glyphs, h {n1-n0}) -> {NAMEF.relative_to(ROOT)}")
    print(f"TB16 {n16} B ({len(cps)} glyphs, h {r1-r0}); TB20 {n20} B ({len(wcp)} glyphs, h {q1-q0}) -> {OUT.relative_to(ROOT)}")
    return 0

if __name__ == "__main__":
    sys.exit(emit())
